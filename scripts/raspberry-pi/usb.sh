#!/usr/bin/env bash
# USB printer provisioning for the Tusj installer (see docs/usb-printers.md).
#
# Sourced by install.sh for --usb. The installer also copies it to <install dir>/tusj-usb.sh,
# where a boot-time unit calls "tusj-usb.sh refresh" so the device paths survive a reboot.
#
#   tusj-usb.sh scan                                      list supported printers (TSV)
#   tusj-usb.sh refresh [--install-dir DIR] -- COMPOSE... rewrite compose.usb.yaml, then up -d
#
# Environment overrides, used by the tests: TUSJ_USB_SYSFS, TUSJ_LSUSB, TUSJ_USB_NO_SUDO,
# TUSJ_UDEV_RULES_DIR, TUSJ_SYSTEM_UNIT_DIR, TUSJ_USER_UNIT_DIR.

usb_override_name=compose.usb.yaml
usb_unit_name=tusj-usb.service
usb_rules_name=99-tusj-usb.rules
usb_brother_vendor=04f9

usb_warn() {
  printf 'Warning: %s\n' "$*" >&2
}

usb_attr() {
  local value=
  { read -r value <"$1"; } 2>/dev/null || value=
  printf '%s' "$value"
}

# Prints one "vendor<TAB>product<TAB>model<TAB>device path" line per supported printer.
# A supported printer is a Brother (04f9) QL model that exposes a USB printer-class (07)
# interface, which is what brother_ql's PyUSB backend looks for. Other Brother devices
# (P-touch, scanners, a QL in Editor Lite mode) are ignored.
usb_scan() {
  local sysfs="${TUSJ_USB_SYSFS:-/sys/bus/usb/devices}" lsusb_cmd="${TUSJ_LSUSB:-lsusb}"
  if [[ -d "$sysfs" ]]; then
    usb_scan_sysfs "$sysfs"
  elif command -v "$lsusb_cmd" >/dev/null 2>&1; then
    usb_scan_lsusb "$lsusb_cmd"
  else
    usb_warn "Cannot detect USB devices: $sysfs does not exist and $lsusb_cmd is not installed."
  fi
  return 0
}

usb_scan_sysfs() {
  local d name vid pid bus dev product model iface is_printer
  for d in "$1"/*; do
    name="${d##*/}"
    [[ "$name" =~ ^[0-9]+-[0-9]+(\.[0-9]+)*$ ]] || continue
    vid="$(usb_attr "$d/idVendor")"
    [[ "${vid,,}" == "$usb_brother_vendor" ]] || continue
    pid="$(usb_attr "$d/idProduct")"
    product="$(usb_attr "$d/product")"
    [[ "$pid" =~ ^[0-9a-fA-F]{4}$ ]] || continue
    [[ "$product" =~ (QL-[0-9A-Za-z]+) ]] || continue
    model="${BASH_REMATCH[1]}"
    is_printer=false
    for iface in "$d/$name":*; do
      if [[ -f "$iface/bInterfaceClass" && "$(usb_attr "$iface/bInterfaceClass")" == 07 ]]; then
        is_printer=true
      fi
    done
    if [[ "$is_printer" != true ]]; then
      usb_warn "$model ($vid:$pid) has no USB printer interface; turn off its Editor Lite mode (hold the Editor Lite button until the lamp goes out)."
      continue
    fi
    bus="$(usb_attr "$d/busnum")"
    dev="$(usb_attr "$d/devnum")"
    [[ "$bus" =~ ^[0-9]+$ && "$dev" =~ ^[0-9]+$ ]] || continue
    printf '%s\t%s\t%s\t/dev/bus/usb/%03d/%03d\n' "${vid,,}" "${pid,,}" "$model" "$((10#$bus))" "$((10#$dev))"
  done
}

usb_scan_lsusb() {
  local line
  local re='^Bus ([0-9]+) Device ([0-9]+): ID ([0-9a-fA-F]{4}):([0-9a-fA-F]{4}) (.*)$'
  while IFS= read -r line; do
    [[ "$line" =~ $re ]] || continue
    [[ "${BASH_REMATCH[3],,}" == "$usb_brother_vendor" ]] || continue
    local bus="${BASH_REMATCH[1]}" dev="${BASH_REMATCH[2]}" vid="${BASH_REMATCH[3]}" pid="${BASH_REMATCH[4]}"
    [[ "${BASH_REMATCH[5]}" =~ (QL-[0-9A-Za-z]+) ]] || continue
    printf '%s\t%s\t%s\t/dev/bus/usb/%03d/%03d\n' "${vid,,}" "${pid,,}" "${BASH_REMATCH[1]}" "$((10#$bus))" "$((10#$dev))"
  done < <("$1" 2>/dev/null)
}
# usb_write_override FILE SCAN_LINE... : replaces FILE with a Compose override that maps only
# the listed devices, or removes FILE when there are none, so stale paths never remain.
usb_write_override() {
  local file="$1" line path tmp
  shift
  local -a paths=()
  for line in "$@"; do
    paths+=("${line##*$'\t'}")
  done
  if ((${#paths[@]} == 0)); then
    rm -f -- "$file"
    return 0
  fi
  tmp="$(mktemp "$file.XXXXXX")" || return 1
  {
    printf '# Generated by the Tusj installer (install.sh --usb); rerun it to update. Do not edit.\n'
    printf 'services:\n  backend:\n    devices:\n'
    while IFS= read -r path; do
      printf '      - %s:%s\n' "$path" "$path"
    done < <(printf '%s\n' "${paths[@]}" | sort -u)
  } >"$tmp" && chmod 0644 "$tmp" && mv -f -- "$tmp" "$file" || { rm -f -- "$tmp"; return 1; }
}

# Runs a command as root: directly if already root, else through sudo (prompting only when
# there is a terminal).
usb_priv() {
  if [[ "$(id -u)" == 0 || -n "${TUSJ_USB_NO_SUDO:-}" ]]; then
    "$@"
  elif ! command -v sudo >/dev/null 2>&1; then
    printf 'sudo is not installed, so "%s" cannot run as root.\n' "$*" >&2
    return 1
  elif [[ -t 0 ]]; then
    sudo "$@"
  else
    sudo -n "$@"
  fi
}

# usb_install_root_file DEST CONTENT : installs the file with mode 0644 unless identical.
usb_install_root_file() {
  local dest="$1" content="$2" tmp rc=0
  if [[ -r "$dest" && "$(<"$dest")" == "$content" ]]; then
    return 0
  fi
  tmp="$(mktemp)" || return 1
  printf '%s\n' "$content" >"$tmp"
  printf 'Installing %s (needs root).\n' "$dest"
  usb_priv install -m 0644 "$tmp" "$dest" || rc=1
  rm -f -- "$tmp"
  return "$rc"
}

# Rootless Podman runs the container as the invoking user (container root maps to that uid),
# so that user must be able to open the device node. The default node is root:root 0664, so
# add a udev rule giving the user ownership of these exact vendor/product IDs only.
# Rules already in the file are kept, so a printer that is switched off keeps its rule.
usb_setup_udev() {
  local owner="$1" rules_dir="${TUSJ_UDEV_RULES_DIR:-/etc/udev/rules.d}" line
  shift
  local dest="$rules_dir/$usb_rules_name" existing=
  local -a rules=()
  [[ -r "$dest" ]] && existing="$(grep -E '^SUBSYSTEM==' "$dest" || true)"
  [[ -n "$existing" ]] && mapfile -t rules <<<"$existing"
  for line in "$@"; do
    IFS=$'\t' read -r vid pid _ <<<"$line"
    rules+=("SUBSYSTEM==\"usb\", ATTR{idVendor}==\"$vid\", ATTR{idProduct}==\"$pid\", OWNER=\"$owner\", MODE=\"0660\"")
  done
  local content
  content="# Tusj: let $owner (rootless Podman) open these Brother QL printers. Generated by install.sh --usb."$'\n'
  content+="$(printf '%s\n' "${rules[@]}" | sort -u)"
  usb_install_root_file "$dest" "$content" || return 1
  if command -v udevadm >/dev/null 2>&1; then
    usb_priv udevadm control --reload-rules &&
      usb_priv udevadm trigger --action=change --subsystem-match=usb --attr-match=idVendor="$usb_brother_vendor" ||
      { usb_warn "Could not reload udev rules; unplug and reconnect the printer."; return 1; }
  else
    usb_warn "udevadm not found; unplug and reconnect the printer to apply the udev rule."
  fi
}

usb_check_access() {
  local line path rc=0
  for line in "$@"; do
    path="${line##*$'\t'}"
    if [[ -e "$path" && ! ( -r "$path" && -w "$path" ) ]]; then
      usb_warn "$path is not readable and writable by $(id -un) yet; unplug and reconnect the printer."
      rc=1
    fi
  done
  return "$rc"
}

# usb_install_boot_unit SCOPE INSTALL_DIR COMPOSE... : a one-shot unit that reruns "refresh"
# at boot, because the bus/device numbers (and so the mapped paths) change between boots.
# SCOPE is "user" (rootless Podman; needs lingering, which the installer enables) or "system".
usb_install_boot_unit() {
  local scope="$1" install_dir="$2" unit dest after
  shift 2
  if [[ "$scope" == user ]]; then
    after="podman-restart.service"
    dest="${TUSJ_USER_UNIT_DIR:-$HOME/.config/systemd/user}"
  else
    after="network-online.target $([[ "$1" == podman* ]] && printf podman-restart.service || printf docker.service)"
    dest="${TUSJ_SYSTEM_UNIT_DIR:-/etc/systemd/system}"
  fi
  unit="[Unit]
Description=Refresh Tusj USB printer mapping
After=$after

[Service]
Type=oneshot
# Stays active after the refresh. KillMode=process is a safety net: Podman's conmon and
# network helpers must never be killed when this unit finishes (they are also started in
# their own scope, see usb_compose).
RemainAfterExit=yes
KillMode=process
TimeoutStartSec=300
WorkingDirectory=$install_dir
ExecStart=\"$install_dir/tusj-usb.sh\" refresh --install-dir \"$install_dir\" -- $*
$([[ "$scope" == system && "$(id -u)" != 0 ]] && printf 'User=%s\n' "$(id -un)")
[Install]
WantedBy=$([[ "$scope" == user ]] && printf default.target || printf multi-user.target)"
  if [[ "$scope" == user ]]; then
    mkdir -p "$dest" && printf '%s\n' "$unit" >"$dest/$usb_unit_name" || return 1
    systemctl --user daemon-reload && systemctl --user enable "$usb_unit_name" >/dev/null 2>&1
  else
    usb_install_root_file "$dest/$usb_unit_name" "$unit" || return 1
    usb_priv systemctl daemon-reload && usb_priv systemctl enable "$usb_unit_name" >/dev/null 2>&1
  fi
}

# usb_compose COMPOSE... : runs Compose. Under systemd (boot unit) Podman is started in its
# own transient scope, so conmon and the rootless network helpers it leaves running do not
# belong to the one-shot unit's cgroup and are not killed when that unit exits.
usb_compose() {
  local -a scope=()
  if [[ -n "${INVOCATION_ID:-}" && "$1" == podman* ]] && command -v systemd-run >/dev/null 2>&1; then
    scope=(systemd-run --quiet --scope --collect)
    [[ "$(id -u)" != 0 ]] && scope+=(--user)
  fi
  "${scope[@]}" "$@"
}

# usb_apply INSTALL_DIR MODE COMPOSE... : makes the containers match compose.usb.yaml.
# The mapping the containers were last created with is kept in .compose.usb.applied. With
# MODE "auto" nothing is touched when it still matches (the normal boot: podman-restart or
# Docker already started the containers). Otherwise (or MODE "force") the containers are
# removed and recreated, since a device mapping can't change in place and "up -d" over
# existing containers makes podman-compose fail with name conflicts. Compose failures are
# returned, and the marker is dropped so the next run retries.
usb_apply() {
  local install_dir="$1" mode="$2" marker override
  shift 2
  marker="$install_dir/.compose.usb.applied"
  override="$install_dir/$usb_override_name"
  cd -- "$install_dir" || return 1
  local -a files=(-f compose.yaml)
  [[ -f "$override" ]] && files+=(-f "$usb_override_name")

  if [[ "$mode" != force && -f "$marker" ]]; then
    if [[ -f "$override" ]] && cmp -s "$override" "$marker"; then
      printf 'USB mapping unchanged; leaving the containers as they are.\n'
      return 0
    elif [[ ! -f "$override" && ! -s "$marker" ]]; then
      printf 'No USB printers, as before; leaving the containers as they are.\n'
      return 0
    fi
  fi

  rm -f -- "$marker"
  printf 'Recreating the Tusj containers with the current USB mapping.\n'
  usb_compose "$@" "${files[@]}" down ||
    usb_warn "'down' failed; trying to start the containers anyway."
  if ! usb_compose "$@" "${files[@]}" up -d; then
    printf 'Starting Tusj failed. It will be retried at the next run of tusj-usb.service.\n' >&2
    return 1
  fi
  if [[ -f "$override" ]]; then
    cp -- "$override" "$marker"
  else
    : >"$marker"
  fi
}

# usb_refresh INSTALL_DIR COMPOSE... : rescan, rewrite the override, and recreate the
# containers only if the mapping changed since they were created.
usb_refresh() {
  local install_dir="$1" line
  shift
  local -a printers=()
  while IFS= read -r line; do
    [[ -n "$line" ]] && printers+=("$line")
  done < <(usb_scan)
  usb_write_override "$install_dir/$usb_override_name" "${printers[@]}" || return 1
  usb_apply "$install_dir" auto "$@"
}

usb_main() {
  local install_dir
  install_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
  case "${1:-}" in
    scan)
      usb_scan
      ;;
    refresh)
      shift
      if [[ "${1:-}" == --install-dir ]]; then
        install_dir="$2"
        shift 2
      fi
      [[ "${1:-}" == -- ]] && shift
      if (($# == 0)); then
        printf 'Usage: %s refresh [--install-dir DIR] -- COMPOSE_COMMAND...\n' "$0" >&2
        return 2
      fi
      usb_refresh "$install_dir" "$@"
      ;;
    *)
      printf 'Usage: %s scan | refresh [--install-dir DIR] -- COMPOSE_COMMAND...\n' "$0" >&2
      return 2
      ;;
  esac
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
  set -euo pipefail
  usb_main "$@"
fi
